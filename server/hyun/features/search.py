# 평가·추천처럼 최신 반응이 필요한 말 — 길·정보 통로 말이 섞여도 검색(예: "도착지 근처 맛난 족발집", "그 영화 재밌어?")
EVAL_WORDS = r"재밌|재미있|볼\s*만|평점|별점|후기|리뷰|반응|평가|호불호|입소문|맛난|맛있는\s*\S*집|유명한\s*\S*집|넷플릭스|티빙|웨이브|디즈니\s*플러스|쿠팡\s*플레이|OTT|예능|드라마\s*(도\s*)?(있|추천|뭐)|시리즈\s*(도\s*)?(있|추천|뭐)"


def needs_search(text):
    from features import feeds
    t = text or ""
    if re.search(EVAL_WORDS, t, re.I):
        return True
    if re.search(r"교통|막혀|길\s*(어때|막)|도착|목적지|가자", t):
        return False
    if feeds.wanted_feeds(t) and not re.search(r"야구|축구|배구|농구|배드민턴|골프|테니스|경기|선수|감독|한국시리즈|월드시리즈", t):
        return False   # 영화·주식·웹툰·웹소설·날씨는 정보 통로가 더 빠르고 정확
    return bool(re.search(SEARCH_WORDS, t, re.I))


TASTE_EVENTS = ("taste_news", "taste_sports")   # 앱이 먼저 건네는 취향 소식(사용자 11-14) — [취향]으로 주제를 골라 웹 검색


def search(msg):
    if msg.get("kind") == "event" and msg.get("text") in TASTE_EVENTS:
        return True
    return msg.get("kind") == "talk" and needs_search(msg.get("text", ""))


